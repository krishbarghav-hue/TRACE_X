from sqlalchemy import (
    Column, BigInteger, String, Integer, Boolean, DateTime,
    TIMESTAMP, ForeignKey, Index, text
)
from sqlalchemy.sql import func
from app.database import Base


class ActivityLog(Base):
    """
    Maps to the 'activity_logs' table in the trace_x database.
    Stores raw browser telemetry from Chrome extension or manual logger.

    event_id:      Stable unique ID generated by the Chrome extension per activity.
                   Used to deduplicate retried/buffered events.
                   Format: "<timestamp_ms>-<domain>-<random>" or a UUID.

    is_active:     True = this activity is currently in progress (heartbeat updates it).
                   False = activity has ended (duration finalized).

    started_at:    Alias for visit_time — when the user arrived on this page.
    ended_at:      Alias for exit_time — when the user left.

    tab_id / window_id: Chrome tab/window IDs for tracking session context.

    activity_type: 'browsing' | 'reading' | 'pdf' | 'video' | 'coding'
    """
    __tablename__ = "activity_logs"

    activity_id      = Column(BigInteger, primary_key=True, autoincrement=True)
    event_id         = Column(String(128), nullable=True, unique=True, index=True)   # deduplication key
    user_id          = Column(BigInteger, ForeignKey("users.user_id", ondelete="CASCADE"), nullable=False)
    source           = Column(String(32), nullable=True, default="chrome")           # "chrome" | "manual"
    tab_id           = Column(Integer, nullable=True)
    window_id        = Column(Integer, nullable=True)
    url              = Column(String(1000), nullable=False)
    domain           = Column(String(255), nullable=False)
    page_title       = Column(String(500), nullable=True)
    activity_type    = Column(String(32), nullable=True, default="browsing")         # browsing | pdf | video | coding
    # Canonical timestamps
    started_at       = Column(DateTime, nullable=True)    # alias for visit_time
    ended_at         = Column(DateTime, nullable=True)    # alias for exit_time
    # Legacy aliases kept for backward compatibility with old code
    visit_time       = Column(DateTime, nullable=True)
    exit_time        = Column(DateTime, nullable=True)
    duration_seconds = Column(Integer, nullable=True)
    is_active        = Column(Boolean, default=False)     # True = currently being tracked
    is_classified    = Column(Boolean, default=False)
    # Optional study tool foreign keys
    course_id        = Column(BigInteger, ForeignKey("courses.course_id", ondelete="SET NULL"), nullable=True)
    topic_id         = Column(BigInteger, ForeignKey("topics.topic_id", ondelete="SET NULL"), nullable=True)
    resource_id      = Column(BigInteger, ForeignKey("resources.resource_id", ondelete="SET NULL"), nullable=True)
    created_at       = Column(TIMESTAMP, server_default=func.now())

    __table_args__ = (
        Index("idx_activity_logs_user_started", "user_id", "started_at"),
        Index("idx_activity_logs_domain", "domain"),
        Index("idx_activity_logs_user_visit_time", "user_id", "visit_time"),
    )
